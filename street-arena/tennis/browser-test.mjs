import {chromium} from "playwright";
import assert from "node:assert/strict";
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 page.on("pageerror",e=>errors.push(e.message));
 const r=await page.goto("http://127.0.0.1:4173/tennis/",{waitUntil:"domcontentloaded",timeout:30000});
 assert.equal(r?.status(),200);
 await page.waitForFunction(()=>window.__matchmakeTennisDebug?.().scene?.courtLength===23.77,{timeout:30000});
 const initial=await page.evaluate(()=>window.__matchmakeTennisDebug());
 assert.equal(initial.scene.courtWidth,8.23);
 assert.equal(initial.scene.netHeight,.914);
 assert.equal(initial.simHz,120);
 assert.ok(initial.scene.buildings>50,"original neon city background");
 await page.locator("#start").click();
 await page.waitForTimeout(350);
 assert.equal(await page.locator("#menu").evaluate(x=>x.classList.contains("hidden")),true);
 await page.keyboard.down("ArrowRight");
 await page.waitForTimeout(500);
 await page.keyboard.up("ArrowRight");
 const moved=await page.evaluate(()=>window.__matchmakeTennisDebug());
 assert.ok(moved.player.x>initial.player.x+.1,"player can move");
 await page.keyboard.down("KeyD");
 await page.waitForTimeout(350);
 await page.keyboard.up("KeyD");
 await page.waitForTimeout(650);
 const rally=await page.evaluate(()=>window.__matchmakeTennisDebug());
 assert.ok(["rally","point","ready","finished"].includes(rally.state),"gameplay state is valid");
 assert.deepEqual(errors,[],"no uncaught script errors");
 await page.screenshot({path:"street-arena/tennis/tennis-browser-smoke.png"});
 console.log("MATCHMAKE TENNIS BROWSER PASS",JSON.stringify({initial,moved,rally}));
}finally{await browser.close();}
